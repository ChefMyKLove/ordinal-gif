function pickRandomDistinct(n) {
  const pool = CARDS.filter(c => c.status === 'available');
  const picked = [];
  const used = new Set();
  while (picked.length < n && picked.length < pool.length) {
    const card = pool[Math.floor(Math.random() * pool.length)];
    if (!used.has(card.num)) { used.add(card.num); picked.push(card); }
  }
  return picked;
}

