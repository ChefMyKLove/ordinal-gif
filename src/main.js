// Global grid speed multiplier — 1.0 = default, 0.5 = half speed, 2.0 = double
let gridSpeedMult = 1.0;

// Each mini card cycles through frames independently at a gentle pace
function animateCard(cardEl, offset, ordinals) {
  const frames = ordinals || BASE_ORDINALS;
  const imgEl = cardEl.querySelector('.mc-frame');
  if (!imgEl) return;
  let frame = offset % frames.length;
  let fading = false;
  const baseInterval = 2200 + (offset * 180);

  function tick() {
    const interval = baseInterval / gridSpeedMult;
    setTimeout(() => {
      if (!fading) {
        fading = true;
        const fadeDur = Math.min(interval * 0.4, 1200 / gridSpeedMult);
        imgEl.style.transition = `opacity ${fadeDur}ms ease-in-out`;
        imgEl.style.opacity = '0';
        setTimeout(() => {
          frame = (frame + 1) % frames.length;
          imgEl.src = API_BASE + frames[frame] + '_0';
          imgEl.style.opacity = '1';
          fading = false;
          tick();
        }, fadeDur);
      } else {
        tick();
      }
    }, interval);
  }

  setTimeout(tick, offset * 320);
}

