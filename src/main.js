const SATOSHIS_PER_BSV = 100000000;
// ORDINALRAINBOWS-Vol.1's backend — currently running in its own dust-level TEST_MODE (see
// lib/pricing.js there), so these prices are small on purpose until that's flipped for launch.
const BACKEND_BASE = 'https://ordinalrainbows.com';
// Price is no longer a flat constant — each card has its own live bump-and-decay curve, served
// by the backend's /api/mint-price.
const PRICE_API = `${BACKEND_BASE}/api/mint-price`;
const PRICE_REFRESH_MS = 45000;

function fmtPrice(sats) {
  if (sats == null) return '…';
  const n = Number(sats);
  return n < 1_000_000 ? `${n.toLocaleString()} sats` : `${(n / SATOSHIS_PER_BSV).toFixed(4)} BSV`;
}

// Splits a settled price the same way lib/pricing.js's splitPayout() does, for display and for
// building the payment outputs. The server is the final authority at settlement time regardless.
function splitPrice(priceSats) {
  const holderSats   = Math.round(priceSats * HOLDER_PCT   / 100);
  const platformSats = Math.round(priceSats * PLATFORM_PCT / 100);
  const creatorSats  = priceSats - holderSats - platformSats; // remainder avoids rounding drift
  return { creatorSats, holderSats, platformSats };
}

// Fetches live prices for every loaded card in one call and stamps card.priceSats + grid/preview.
async function fetchPrices() {
  try {
    const resp = await fetch(PRICE_API, {
      method: 'POST', headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ card_ids: CARDS.map(c => c.pieceId) }),
    });
    if (!resp.ok) throw new Error(`HTTP ${resp.status}`);
    const { prices } = await resp.json();
    CARDS.forEach(card => {
      const p = prices[card.pieceId];
      if (p) { card.priceSats = Number(p.price_sats); card.windowOpen = p.window_open; }
    });
    refreshPriceDisplays();
  } catch (err) {
    console.warn('[prices] fetch failed (will retry):', err.message);
  }
}

function refreshPriceDisplays() {
  CARDS.forEach(card => {
    const el = collGrid?.querySelector(`[data-num="${card.num}"] .mc-price`);
    if (el) el.textContent = fmtPrice(card.priceSats);
  });
  if (selectedCard) previewPrice.textContent = fmtPrice(selectedCard.priceSats);
}

